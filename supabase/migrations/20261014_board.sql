-- 게시판: 글·댓글을 DB로 관리 (작성자 포함)
create table if not exists public.board_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('공지사항', '자유', '신고', '후기')),
  title text not null check (char_length(title) between 1 and 100),
  content text not null check (char_length(content) between 1 and 5000),
  pinned boolean not null default false,
  views integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists board_posts_created_at_idx on public.board_posts (created_at desc);

create table if not exists public.board_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.board_posts(id) on delete cascade,
  author_id uuid not null references auth.users(id) on delete cascade,
  content text not null check (char_length(content) between 1 and 500),
  created_at timestamptz not null default now()
);
create index if not exists board_comments_post_id_idx on public.board_comments (post_id, created_at);

alter table public.board_posts enable row level security;
alter table public.board_comments enable row level security;

-- 글·댓글은 로그인한 회원 누구나 읽고, 본인 것만 쓰고 지운다
create policy "board_posts select" on public.board_posts for select to authenticated using (true);
create policy "board_posts insert own" on public.board_posts for insert to authenticated
  with check (author_id = auth.uid() and pinned = false and views = 0);
create policy "board_posts update own" on public.board_posts for update to authenticated
  using (author_id = auth.uid()) with check (author_id = auth.uid());
create policy "board_posts delete own" on public.board_posts for delete to authenticated using (author_id = auth.uid());

create policy "board_comments select" on public.board_comments for select to authenticated using (true);
create policy "board_comments insert own" on public.board_comments for insert to authenticated
  with check (author_id = auth.uid());
create policy "board_comments delete own" on public.board_comments for delete to authenticated using (author_id = auth.uid());

-- 조회수: 상세를 열 때 1 증가 (조회수 칸은 직접 수정 못 함)
revoke update on public.board_posts from authenticated;
grant update (title, content, category) on public.board_posts to authenticated;

create or replace function public.increment_board_view(p_post_id bigint)
returns void
language sql
security definer
set search_path = public
as $$
  update public.board_posts set views = views + 1 where id = p_post_id;
$$;
revoke all on function public.increment_board_view(bigint) from public, anon;
grant execute on function public.increment_board_view(bigint) to authenticated;

